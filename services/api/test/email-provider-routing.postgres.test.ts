import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {randomUUID} from "node:crypto";
import {mkdtemp,readFile,rm} from "node:fs/promises";
import {createServer} from "node:net";
import {tmpdir} from "node:os";
import {join,resolve,relative} from "node:path";
import test from "node:test";
import Fastify from "fastify";
import pg from "pg";
import {pool} from "../src/db.js";
import {config} from "../src/config.js";
import {signToken,decryptAtRest} from "../src/security.js";
import {registerEmailProviderRoutes} from "../src/email-provider-routes.js";
import {resolveEmailProvider} from "../src/email-provider-routing.js";

// 只启动并清理专用临时实例，不使用 DATABASE_URL，不连接业务数据库。
test("PostgreSQL：旧配置迁移、多实例、渠道绑定与管理接口",{skip:!process.env.EMAIL_PROVIDER_PG_BIN},async t=>{
  const directory=await mkdtemp(join(tmpdir(),"relay-email-provider-test-"));
  const bin=process.env.EMAIL_PROVIDER_PG_BIN!;
  const run=(name:string,args:string[])=>execFileSync(join(bin,process.platform==="win32"?`${name}.exe`:name),args,{windowsHide:true,stdio:"ignore",timeout:60000});
  const listener=createServer();await new Promise<void>(done=>listener.listen(0,"127.0.0.1",done));
  const port=(listener.address() as {port:number}).port;await new Promise<void>(done=>listener.close(()=>done()));
  const db=new pg.Pool({host:"127.0.0.1",port,user:"postgres",database:"postgres"});
  const app=Fastify();let started=false;
  try{
    run("initdb",["-D",directory,"-A","trust","-U","postgres","--encoding=UTF8","--no-locale"]);
    run("pg_ctl",["-D",directory,"-l",join(directory,"postgres.log"),"-o",`-h 127.0.0.1 -p ${port}`,"-w","start"]);started=true;
    await db.query(`CREATE TABLE users(id uuid PRIMARY KEY);
      CREATE TABLE channel_accounts(id uuid PRIMARY KEY);
      CREATE TABLE email_provider_settings(provider text PRIMARY KEY,enabled boolean,config jsonb,secret_encrypted text,updated_by uuid,created_at timestamptz DEFAULT now(),updated_at timestamptz DEFAULT now());
      CREATE TABLE audit_log(actor_type text,actor_id uuid,action text,target_type text,target_id uuid,metadata jsonb);
      INSERT INTO email_provider_settings(provider,enabled,config,secret_encrypted) VALUES('smtp',true,'{"fromName":"旧 SMTP","fromEmail":"old@example.com"}','old-secret'),('resend',false,'{}','old-resend-secret');`);
    const migration=await readFile(new URL("../../../infra/postgres/migrations/103_email_provider_instances.sql",import.meta.url),"utf8");
    await db.query(migration);await db.query(migration);
    assert.equal((await db.query("SELECT * FROM email_provider_instances")).rowCount,2);
    const migrated=(await db.query("SELECT * FROM email_provider_instances WHERE is_default")).rows[0];
    assert.equal(migrated.provider,"smtp");assert.equal(migrated.secret_encrypted,"old-secret");
    const actor=randomUUID(),accounts=[randomUUID(),randomUUID(),randomUUID()];
    await db.query("INSERT INTO users VALUES($1)",[actor]);
    for(const id of accounts)await db.query("INSERT INTO channel_accounts VALUES($1)",[id]);
    t.mock.method(pool,"query",db.query.bind(db));t.mock.method(pool,"connect",db.connect.bind(db));
    registerEmailProviderRoutes(app);
    const headers={authorization:`Bearer ${signToken({sub:actor,role:"admin"},config.JWT_SECRET)}`};
    const base="/api/v1/admin/email-providers";
    const save=(id:string,payload:Record<string,unknown>)=>app.inject({method:"PUT",url:`${base}/${id}`,headers,payload});
    const binding=(index:number,providerId:string|null)=>app.inject({method:"PUT",url:`/api/v1/admin/email-provider-bindings/${accounts[index]}`,headers,payload:{providerId}});
    const payload={name:"Resend A",provider:"resend",enabled:true,isDefault:false,fromName:"销售",fromEmail:"sales@example.com",secret:"test-resend-secret"};
    const resendA=randomUUID(),resendB=randomUUID(),smtpB=randomUUID();
    assert.equal((await app.inject({url:base})).statusCode,401);
    assert.equal((await app.inject({url:base,headers:{authorization:`Bearer ${signToken({sub:actor,role:"agent"},config.JWT_SECRET)}`}})).statusCode,403);
    assert.equal((await save("not-uuid",payload)).statusCode,400);
    assert.equal((await save(resendA,{...payload,secret:undefined})).statusCode,400);
    assert.equal((await save(resendA,{...payload,enabled:false,isDefault:true})).statusCode,400);
    assert.equal((await save(resendA,payload)).statusCode,200);
    assert.equal((await save(resendB,{...payload,name:"Resend B",isDefault:true})).statusCode,200);
    assert.equal((await save(smtpB,{...payload,name:"SMTP B",provider:"smtp",enabled:false,host:"smtp.example.com",port:587,tls:"starttls"})).statusCode,200);
    // 连接验证不访问外部 SMTP；用 SQL 启用独立实例检查真实路由与数据库约束。
    await db.query("UPDATE email_provider_instances SET enabled=true WHERE id=$1",[smtpB]);
    assert.equal((await db.query("SELECT * FROM email_provider_instances WHERE provider='smtp' AND enabled")).rowCount,2);
    assert.equal((await db.query("SELECT * FROM email_provider_instances WHERE provider='resend' AND enabled")).rowCount,2);
    assert.equal((await db.query("SELECT * FROM email_provider_instances WHERE is_default")).rowCount,1);
    const encrypted=(await db.query("SELECT secret_encrypted FROM email_provider_instances WHERE id=$1",[resendA])).rows[0].secret_encrypted;
    assert.notEqual(encrypted,payload.secret);assert.equal(decryptAtRest(encrypted,config.DATA_ENCRYPTION_KEY),payload.secret);
    assert.equal((await save(resendA,{...payload,secret:undefined,name:"更新名称"})).statusCode,200);
    assert.equal((await db.query("SELECT secret_encrypted FROM email_provider_instances WHERE id=$1",[resendA])).rows[0].secret_encrypted,encrypted);
    assert.equal((await save(resendA,{...payload,provider:"smtp",host:"smtp.example.com",port:587,tls:"starttls"})).statusCode,409);
    assert.equal((await binding(0,resendA)).statusCode,200);assert.equal((await binding(1,smtpB)).statusCode,200);
    assert.equal((await resolveEmailProvider(db,accounts[0]))?.id,resendA);
    assert.equal((await resolveEmailProvider(db,accounts[1]))?.id,smtpB);
    assert.equal((await resolveEmailProvider(db,accounts[2]))?.id,resendB);
    const list=await app.inject({url:base,headers});assert.equal(list.statusCode,200);
    assert.equal(list.json().bindings.length,2);assert.equal(list.json().data.length,5);
    assert.equal(list.body.includes("test-resend-secret"),false);assert.equal(list.body.includes(encrypted),false);
    const snapshot=await resolveEmailProvider(db,accounts[0]);
    assert.equal((await save(resendA,{...payload,enabled:false,secret:undefined})).statusCode,200);
    await assert.rejects(resolveEmailProvider(db,accounts[0]),{message:"channel_email_provider_unavailable"});
    assert.equal((await binding(2,resendA)).statusCode,409);
    assert.equal(snapshot?.secret_encrypted,encrypted);assert.equal(snapshot?.config.fromEmail,payload.fromEmail);
    assert.equal((await binding(0,null)).statusCode,200);
    assert.equal((await resolveEmailProvider(db,accounts[0]))?.id,resendB);
    await db.query("UPDATE email_provider_instances SET is_default=false");
    assert.equal(await resolveEmailProvider(db,accounts[0]),null);
    await db.query(migration);
    assert.equal((await db.query("SELECT * FROM email_provider_instances")).rowCount,5);
    assert.equal((await db.query("SELECT * FROM email_provider_settings")).rowCount,2);
  }finally{
    await app.close();await db.end();
    if(started)run("pg_ctl",["-D",directory,"-m","fast","-w","stop"]);
    const target=resolve(directory),within=relative(resolve(tmpdir()),target);
    if(within.startsWith("relay-email-provider-test-")&&!within.includes(".."))await rm(target,{recursive:true,force:true});
  }
});
